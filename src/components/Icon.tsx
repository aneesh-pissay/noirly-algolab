export function iconComponent(name: string): LucideIcon {
  return ICONS[name] ?? CircleDot;
}

/**
 * A Material-named icon rendered with lucide. Sized in `em`, so the text-size
 * classes the old icon font relied on (`text-sm`, `text-[20px]`) still apply.
 * Decorative by default; pass `label` when the icon carries meaning alone.
 */
export function Icon({ name, className, label }: { name: string; className?: string; label?: string }) {
  return createElement(iconComponent(name), {
    size: "1em",
    strokeWidth: 1.75,
    className: ["inline-block shrink-0", className].filter(Boolean).join(" "),
    ...(label ? { "aria-label": label, role: "img" } : { "aria-hidden": true }),
  });
}

const TRACK_ICONS: Record<TrackId, LucideIcon> = {
  "data-structures": Box,
  algorithms: Workflow,
  patterns: Spline,
};

/** The icon for a curriculum track (kept out of the data file on purpose). */
export function iconFor(trackId: TrackId): LucideIcon {
  return TRACK_ICONS[trackId] ?? GitFork;
}
